#!/bin/sh
# Prepare the database, then hand over to the CMD (supervisord).
set -eu

# nginx trusts the client address and scheme (X-Forwarded-For/-Proto) only from the
# proxies in TRUSTED_PROXIES (comma separated addresses or CIDR ranges, e.g. the TLS
# proxy in front). Without it the connection itself counts: a client cannot claim
# another address or HTTPS. Written to /tmp because the root filesystem is read-only.
trust=/tmp/nginx-trusted-proxies.conf
rm -f "$trust.realip"
echo "# Generated by entrypoint.sh from TRUSTED_PROXIES." > "$trust"
echo "geo \$realip_remote_addr \$from_trusted_proxy {" >> "$trust"
echo "    default 0;" >> "$trust"
for proxy in $(echo "${TRUSTED_PROXIES:-}" | tr ',' ' '); do
    echo "    $proxy 1;" >> "$trust"
    echo "set_real_ip_from $proxy;" >> "$trust.realip"
done
echo "}" >> "$trust"
if [ -f "$trust.realip" ]; then
    cat "$trust.realip" >> "$trust" && rm "$trust.realip"
    echo "real_ip_header X-Forwarded-For;" >> "$trust"
    echo "real_ip_recursive on;" >> "$trust"
elif echo "${APP_URLS:-}" | grep -q 'https://'; then
    echo "Warning: APP_URLS has https URLs but TRUSTED_PROXIES is empty; set it to the TLS proxy's address." >&2
fi

# Production settings that are plainly wrong stop the start here, not at the first request.
python manage.py check --deploy --fail-level ERROR
python manage.py wait_for_db --timeout 60
python manage.py migrate --noinput
python manage.py ensure_superuser

if [ "${APP_DEMO_DATA:-false}" = "true" ]; then
    # Only seeds an empty database; refuses (and we continue) once data exists.
    python manage.py seed_demo || echo "Demo data not seeded (database not empty)."
fi

exec "$@"
